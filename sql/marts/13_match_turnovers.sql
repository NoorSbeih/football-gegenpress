CREATE OR REPLACE TABLE marts.match_turnovers AS
SELECT
    w.turnover_id,
    w.match_id,
    w.period,
    w.losing_team,
    w.losing_team_id,
    w.winning_team,
    w.loss_minute,
    w.loss_second,
    w.loss_index,
    w.loss_zone,
    w.loss_x,
    w.loss_y,
    w.regained,
    w.time_to_regain_s,
    w.regain_x,
    w.regain_y,
    w.regain_zone,
    w.pressed,
    w.time_to_first_pressure_s,
    w.censored_by_period,
    w.regained_5,
    w.time_to_regain_5_s,
    m.match_date,
    m.home_team,
    m.away_team,
    m.home_team_id,
    m.away_team_id,
    m.home_score,
    m.away_score,
    m.competition_stage
FROM marts.press_windows AS w
INNER JOIN raw.matches AS m ON m.match_id = w.match_id;
